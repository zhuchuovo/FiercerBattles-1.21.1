"""Write the Zombie Lord's left fist path through the throw clip into ZombieLordGrip.java (system Python + numpy).

python tools/zombie_lord_hand_path.py

Reads the exported game clip (assets/fiercerbattles/zombie_lord/clips/throw.json) and model.json, takes the centre of
the left gauntlet (the 5 px cube at the end of leftArm_bend) at every tick and converts it from vanilla model space
(pixels, y down, feet at y = 24, -x = the boss's right, -z = its front) to the boss's frame in blocks at render
scale: right, up, forward from its feet. The table replaces the block between the BEGIN/END GENERATED markers, so
the server, which never loads client assets, holds a grabbed victim exactly where the client draws the fist.
Run it again after re-exporting throw.json.
"""
import json
from pathlib import Path

import numpy as np

REPOSITORY = Path(__file__).resolve().parents[1]
ASSETS = REPOSITORY / "src/main/resources/assets/fiercerbattles/zombie_lord"
TARGET = REPOSITORY / "src/main/java/com/fiercerbattles/boss/ZombieLordGrip.java"
CHANNEL = "leftArm_bend"
GAUNTLET = 5.0   # px, the gauntlet cube at the end of the forearm
SCALE = 1.5 / 16.0   # ZombieLord.RENDER_SCALE / pixels per block


def rotate(q, v):
    x, y, z, w = q
    u = np.array([x, y, z])
    return v + 2 * np.cross(u, np.cross(u, v) + w * v)


def main():
    model = json.loads((ASSETS / "model.json").read_text(encoding="utf-8"))
    clip = json.loads((ASSETS / "clips/throw.json").read_text(encoding="utf-8"))
    points = np.array([face[3 + 5 * i:6 + 5 * i] for face in model["objects"][CHANNEL]["faces"] for i in range(4)])
    low, high = points.min(0), points.max(0)
    fist = np.array([(low[0] + high[0]) / 2, high[1] - GAUNTLET / 2, (low[2] + high[2]) / 2])
    samples = clip["parts"][CHANNEL]
    per_tick = round(1 / clip["sample_step"])
    rows = []
    for tick in range(clip["duration_ticks"] + 1):
        sample = samples[min(len(samples) - 1, tick * per_tick)]
        p = np.array(sample[:3]) + rotate(np.array(sample[3:]), fist)
        rows.append((-p[0] * SCALE, (24.0 - p[1]) * SCALE, -p[2] * SCALE))
    lines = ["    // BEGIN GENERATED by tools/zombie_lord_hand_path.py from clips/throw.json (%s): right, up, forward per tick"
             % clip["source_sha256"][:12],
             "    private static final float[] THROW_FIST = {"]
    for tick, (r, u, f) in enumerate(rows):
        lines.append("            %.3fF, %.3fF, %.3fF,%s" % (r, u, f, "  // %d" % tick if tick % 5 == 0 else ""))
    lines += ["    };", "    // END GENERATED"]
    source = TARGET.read_text(encoding="utf-8")
    start = source.index("    // BEGIN GENERATED")
    end = source.index("    // END GENERATED") + len("    // END GENERATED")
    TARGET.write_text(source[:start] + "\n".join(lines) + source[end:], encoding="utf-8", newline="")
    print("wrote %d ticks to %s" % (len(rows), TARGET.name))
    for tick in (0, 6, 11, 23, 27):
        print("  tick %2d fist right %.2f up %.2f forward %.2f" % (tick, *rows[tick]))


if __name__ == "__main__":
    main()
