"""Write the Iron Sentinel's tracked points into IronSentinelPoints.java (system Python).

python tools/iron_sentinel_points.py

Reads the "points" block tools/export_iron_sentinel.py puts in the exported clips (assets/fiercerbattles/
iron_sentinel/clips): the saw's impale point through saw_impale and saw_cannon_impale (where a skewered victim
sits, and how fast it leaves the blade at the release), and the cannon's muzzle and bore direction at the shots of
skill_cannon / saw_cannon (frame 48, the fire loop's shot) and cannon_sky / saw_cannon_sky. Points go from vanilla
model space (pixels, y down, feet at y = 24, -x = the boss's right, -z = its front) to the boss's frame in blocks at
scale 1: right, up, forward from its feet (IronSentinel multiplies by its render scale). The tables replace the
block between the BEGIN/END GENERATED markers, so the server, which never loads client assets, places shells and
skewered victims exactly where the client draws the cannon and the saw. Run it again after re-exporting those clips.
"""
import json
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parents[1]
CLIPS = REPOSITORY / "src/main/resources/assets/fiercerbattles/iron_sentinel/clips"
TARGET = REPOSITORY / "src/main/java/com/fiercerbattles/boss/IronSentinelPoints.java"
IMPALES = {"IMPALE": "saw_impale", "CANNON_IMPALE": "saw_cannon_impale"}
RELEASE_FRAME = 55
MUZZLES = {"FIRE_MUZZLE": ("skill_cannon", [48]), "SAW_FIRE_MUZZLE": ("saw_cannon", [48]),
           "SKY_MUZZLE": ("cannon_sky", [8, 13, 18]), "SAW_SKY_MUZZLE": ("saw_cannon_sky", [8, 13, 18])}


def local(point):
    x, y, z = point[:3]
    return -x / 16.0, (24.0 - y) / 16.0, -z / 16.0


def direction(point):
    dx, dy, dz = point[3:6]
    return -dx, -dy, -dz


def floats(values):
    return ", ".join("%.4fF" % v for v in values)


def main():
    lines = []
    sources = []
    for name, clip_name in IMPALES.items():
        clip = json.loads((CLIPS / (clip_name + ".json")).read_text(encoding="utf-8"))
        sources.append("%s %s" % (clip_name, clip["source_sha256"][:12]))
        rows = [local(p) for p in clip["points"]["impale"]]
        before, after = rows[RELEASE_FRAME - 1], rows[RELEASE_FRAME + 1]
        release = [(a - b) / 2 for a, b in zip(after, before)]
        lines.append("    /** %s: the impale point per clip frame (right, up, forward). */" % clip_name)
        lines.append("    static final float[] %s = {" % name)
        for tick, row in enumerate(rows):
            lines.append("            %s,%s" % (floats(row), "  // %d" % tick if tick % 5 == 0 else ""))
        lines.append("    };")
        lines.append("    /** %s: the impale point's velocity at the release (blocks per tick). */" % clip_name)
        lines.append("    static final float[] %s_RELEASE = {%s};" % (name, floats(release)))
    for name, (clip_name, ticks) in MUZZLES.items():
        clip = json.loads((CLIPS / (clip_name + ".json")).read_text(encoding="utf-8"))
        sources.append("%s %s" % (clip_name, clip["source_sha256"][:12]))
        lines.append("    /** %s frames %s: muzzle (right, up, forward) then bore direction, per shot. */" % (
            clip_name, ", ".join(map(str, ticks))))
        lines.append("    static final float[] %s = {" % name)
        for tick in ticks:
            point = clip["points"]["muzzle"][tick]
            lines.append("            %s, %s,  // %d" % (floats(local(point)), floats(direction(point)), tick))
        lines.append("    };")
    header = ["    // BEGIN GENERATED by tools/iron_sentinel_points.py from " + ", ".join(sources)]
    source = TARGET.read_text(encoding="utf-8")
    start = source.index("    // BEGIN GENERATED")
    end = source.index("    // END GENERATED") + len("    // END GENERATED")
    TARGET.write_text(source[:start] + "\n".join(header + lines + ["    // END GENERATED"]) + source[end:],
                      encoding="utf-8", newline="")
    print("wrote", TARGET.name)
    for name, clip_name in IMPALES.items():
        clip = json.loads((CLIPS / (clip_name + ".json")).read_text(encoding="utf-8"))
        for tick in (10, 14, 24, 55):
            print("  %s frame %d: right %.2f up %.2f forward %.2f" % (name, tick, *local(clip["points"]["impale"][tick])))


if __name__ == "__main__":
    main()
